// ---- Printings (Addendum 2 §2). A "printing" is a base card or an alternate-art variant of one.
// allPrintings(): the 151 base cards followed by the 25 variants with inherited fields; every entry carries
//   printing:true, seed, number and baseId. Variants override id, rarity, number, scene, flavor (their own line).
// cardOf(id): the base card for a base id or a variant id (undefined if unknown).
// isVariant(id): true when the id names an Illustration Rare or Secret Illustration Rare printing.
function allPrintings() {
  const bases = CARD_SET.cards.map(function (c) { return Object.assign({}, c, { printing: true, baseId: c.id }); });
  const variants = CARD_SET.variants.map(function (v) {
    const b = cardOf(v.base);
    return Object.assign({}, b, {
      id: v.id, baseId: b.id, base: v.base, rarity: v.rarity, number: v.number, seed: v.seed,
      scene: v.scene, flavor: v.flavor, printing: true
    });
  });
  return bases.concat(variants);
}
function cardOf(id) {
  for (var i = 0; i < CARD_SET.cards.length; i++) if (CARD_SET.cards[i].id === id) return CARD_SET.cards[i];
  for (var j = 0; j < CARD_SET.variants.length; j++) if (CARD_SET.variants[j].id === id) return cardOf(CARD_SET.variants[j].base);
  return undefined;
}
function isVariant(id) {
  for (var i = 0; i < CARD_SET.variants.length; i++) {
    var v = CARD_SET.variants[i];
    if (v.id === id) return v.rarity === "IR" || v.rarity === "SIR";
  }
  return false;
}
